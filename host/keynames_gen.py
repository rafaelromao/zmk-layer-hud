"""hud/keynames.js, written from the key vocabulary (host/keynames.py), for the pages.

The board names a typed key by its glyph and finds it under whatever spelling the drawing uses; the
strip draws named keys and chords by their glyphs; and the touch keyboard runs a virtual firmware in
the page (hud/engine.js) whose reports hud/hidtext.js turns into characters and the feed's key
events, the way host/hiddecode.py does for the physical keyboard. All of it reads the vocabulary
written out here rather than copied by hand, so the pages and the feed cannot drift.
keynames_gen_test.py fails when the page's copy is behind.

    python3 host/keynames_gen.py           print it
    python3 host/keynames_gen.py --write   write hud/keynames.js
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from hiddecode import DEAD_KEY_MS  # noqa: E402
from keynames import (ALT_CHARS, ALTGR_CHARS, CHARS, CONTROL_CHARS, DEAD_KEY_SPECIAL, DEAD_KEYS,  # noqa: E402
                      GLYPHS, MOD_BITS, MOD_GLYPHS, NAMED, RALT, SPELLINGS)

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "hud", "keynames.js")


def tables():
    """The vocabulary's tables in JSON's shapes: usages as decimal keys, a (usage, shifted) pair as
    "usage,0" or "usage,1", a dead key and its letter as their two characters."""
    def pair(table):
        return {f"{u},{int(s)}": ch for (u, s), ch in sorted(table.items())}
    return {
        "MOD_BITS": {str(b): n for b, n in sorted(MOD_BITS.items())},
        "CHARS": {str(u): list(cs) for u, cs in sorted(CHARS.items())},
        "NAMED": {str(u): n for u, n in sorted(NAMED.items())},
        "GLYPHS": GLYPHS,
        "SPELLINGS": SPELLINGS,
        "MOD_GLYPHS": MOD_GLYPHS,
        "CONTROL_CHARS": {str(u): c for u, c in sorted(CONTROL_CHARS.items())},
        "ALT_CHARS": pair(ALT_CHARS),
        "ALTGR_CHARS": pair(ALTGR_CHARS),
        "RALT": RALT,
        "DEAD_KEYS": dict(sorted(DEAD_KEYS.items())),
        "DEAD_KEY_SPECIAL": {d + c: ch for (d, c), ch in sorted(DEAD_KEY_SPECIAL.items())},
        "DEAD_KEY_MS": DEAD_KEY_MS,
    }


def _js(value):
    return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))


def generate():
    lines = []
    for name, table in tables().items():
        if not isinstance(table, dict) or len(_js(table)) < 90:
            lines.append(f"    {_js(name)}: {_js(table)},")
            continue
        lines.append(f"    {_js(name)}: {{")
        lines += [f"      {_js(k)}: {_js(v)}," for k, v in table.items()]
        lines[-1] = lines[-1].rstrip(",")
        lines.append("    },")
    lines[-1] = lines[-1].rstrip(",")
    body = "{\n" + "\n".join(lines) + "\n  }"
    return (
        "/* zmk-layer-hud — the key vocabulary (host/keynames.py), for the pages: what a key report types,\n"
        " * the named keys' names, glyphs and spellings, and the modifiers' glyphs.\n"
        " * Generated by host/keynames_gen.py; do not edit -- `make keynames` writes it again.\n"
        " * DOM-free: the page, the strip alone (keys.html), node and a bare JavaScriptCore read it. */\n"
        "(function (root) {\n"
        "  \"use strict\";\n"
        f"  const T = {body};\n"
        "  // The named key a legend stands for, however the drawing spells it, or null (keynames.name_of).\n"
        "  T.nameOf = legend => (typeof legend === \"string\" && T.SPELLINGS[legend.replace(/\\s+/g, \"\").toLowerCase()]) || null;\n"
        "  if (typeof module === \"object\" && module.exports) module.exports = T;\n"
        "  else root.ZmkKeyNames = T;\n"
        "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n"
    )


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = generate()
    if "--write" in argv:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT)}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
