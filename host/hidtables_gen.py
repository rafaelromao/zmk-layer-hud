"""hud/hidtables.js, written from hudfeed's own tables: what a key report types, for the page.

The touch keyboard runs a virtual firmware in the page (hud/engine.js), and what it sends is what a
keyboard sends -- report snapshots, a modifier byte and the usages held. A text-only sink (an iPad's
keyboard extension inserts text, it cannot press keys) needs those turned into characters, and the
typed-keys strip needs them as the feed's key events; hud/hidtext.js does both, the way
hudfeed.SignalDecoder does for the physical keyboard. Its tables are hudfeed's, written out here
rather than copied by hand, so the two cannot drift. hidtables_test.py fails when the page's copy
is behind.

    python3 host/hidtables_gen.py           print it
    python3 host/hidtables_gen.py --write   write hud/hidtables.js
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from hiddecode import DEAD_KEY_MS  # noqa: E402
from keynames import (ALT_CHARS, ALTGR_CHARS, CHARS, CONTROL_CHARS, DEAD_KEY_SPECIAL, DEAD_KEYS,  # noqa: E402
                      MOD_BITS, NAMED, RALT)

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "hud", "hidtables.js")


def tables():
    """hudfeed's tables in JSON's shapes: usages as decimal keys, a (usage, shifted) pair as
    "usage,0" or "usage,1", a dead key and its letter as their two characters."""
    def pair(table):
        return {f"{u},{int(s)}": ch for (u, s), ch in sorted(table.items())}
    return {
        "MOD_BITS": {str(b): n for b, n in sorted(MOD_BITS.items())},
        "CHARS": {str(u): list(cs) for u, cs in sorted(CHARS.items())},
        "NAMED": {str(u): n for u, n in sorted(NAMED.items())},
        "CONTROL_CHARS": {str(u): c for u, c in sorted(CONTROL_CHARS.items())},
        "ALT_CHARS": pair(ALT_CHARS),
        "ALTGR_CHARS": pair(ALTGR_CHARS),
        "RALT": RALT,
        "DEAD_KEYS": dict(sorted(DEAD_KEYS.items())),
        "DEAD_KEY_SPECIAL": {d + c: ch for (d, c), ch in sorted(DEAD_KEY_SPECIAL.items())},
        "DEAD_KEY_MS": DEAD_KEY_MS,
    }


def _js(value):
    return json.dumps(value, ensure_ascii=False, separators=(", ", ": "))


def generate():
    lines = []
    for name, table in tables().items():
        if not isinstance(table, dict) or len(_js(table)) < 90:
            lines.append(f"    {_js(name)}: {_js(table)},")
            continue
        lines.append(f"    {_js(name)}: {{")
        lines += [f"      {_js(k)}: {_js(v)}," for k, v in table.items()]
        lines[-1] = lines[-1].rstrip(",")
        lines.append("    },")
    lines[-1] = lines[-1].rstrip(",")
    body = "{\n" + "\n".join(lines) + "\n  }"
    return (
        "/* zmk-layer-hud — what a key report types: hudfeed's tables (host/hudfeed.py), for the page.\n"
        " * Generated by host/hidtables_gen.py; do not edit -- `make hidtables` writes it again.\n"
        " * DOM-free: hud/hidtext.js reads it in the page, under node, and in a bare JavaScriptCore. */\n"
        "(function (root) {\n"
        "  \"use strict\";\n"
        f"  const T = {body};\n"
        "  if (typeof module === \"object\" && module.exports) module.exports = T;\n"
        "  else root.ZmkHidTables = T;\n"
        "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n"
    )


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = generate()
    if "--write" in argv:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT)}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
